// Merge __FLASH_* fragments. Module fragments (__FLASH_M00..__FLASH_M18) override letter fragments
// for their module: items with module === NN from letter fragments are dropped if a module fragment exists.
(function() {
  var letterCards = [];
  Object.keys(window).filter(function(k) { return k.indexOf('__FLASH_') === 0 && !/^__FLASH_M\d/.test(k); }).forEach(function(k) {
    if (Array.isArray(window[k])) letterCards = letterCards.concat(window[k]);
  });
  var moduleOverrides = {};
  Object.keys(window).filter(function(k) { return /^__FLASH_M(\d{2})/.test(k); }).forEach(function(k) {
    var m = k.match(/^__FLASH_M(\d{2})/);
    if (m && Array.isArray(window[k])) moduleOverrides[m[1]] = window[k];
  });
  // Drop letter cards for any module that has an override
  letterCards = letterCards.filter(function(c) { return !moduleOverrides[c.module]; });
  window.FLASHCARDS = letterCards;
  Object.keys(moduleOverrides).forEach(function(mod) {
    window.FLASHCARDS = window.FLASHCARDS.concat(moduleOverrides[mod]);
  });
})();
